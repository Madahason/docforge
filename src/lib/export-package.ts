export function buildThumbnailConceptsTxt(thumb: ThumbnailRecord): string {
  const lines: string[] = ["THUMBNAIL CONCEPTS", "Generated by DocForge", ""];
  const concepts = (thumb.concepts ?? []) as Record<string, unknown>[];
  concepts.forEach((c, i) => {
    const selected = thumb.selected_concept_index === i ? " (SELECTED)" : "";
    lines.push(`--- CONCEPT ${i + 1}${selected} ---`);
    if (c.title_copy) lines.push(`Title overlay: ${String(c.title_copy)}`);
    if (c.concept) lines.push(`Concept: ${String(c.concept)}`);
    if (c.visual_description) lines.push(`Visual: ${String(c.visual_description)}`);
    if (c.image_prompt) lines.push(`Image prompt: ${String(c.image_prompt)}`);
    if (c.image_url) lines.push(`Generated image: ${String(c.image_url)}`);
    lines.push("");
  });
  if (thumb.custom_title_copy) lines.push(`Custom title copy: ${thumb.custom_title_copy}`);
  return lines.join("\n");
}

export function buildAiClipPromptsTxt(scenes: Scene[], clips: Clip[]): string {
  const lines: string[] = ["AI CLIP PROMPTS", "Generated by DocForge", ""];
  for (const s of scenes) {
    const clip = clips.find((c) => c.scene_id === s.id);
    if (!s.clip_brief && !clip?.source_url) continue;
    lines.push(`SCENE ${s.scene_index + 1}`);
    lines.push(`Visual Job: ${s.visual_job ?? "—"}`);
    lines.push(`Subject: ${s.clip_brief?.subject ?? "—"}`);
    if (s.clip_brief?.mood?.length) lines.push(`Mood: ${s.clip_brief.mood.join(", ")}`);
    if (s.clip_brief?.avoid?.length) lines.push(`Avoid: ${s.clip_brief.avoid.join(", ")}`);
    if (s.clip_brief?.color_temperature) lines.push(`Color: ${s.clip_brief.color_temperature}`);
    if (s.clip_brief?.suggested_search_terms?.length) {
      lines.push("Search Terms:");
      for (const t of s.clip_brief.suggested_search_terms) lines.push(`  - ${t}`);
    }
    lines.push("---", "");
  }
  return lines.join("\n");
}

export function buildFullVideoSrt(scenes: Scene[], captions: CaptionRecord[]): string {
  const ordered = [...scenes].sort((a, b) => a.scene_index - b.scene_index);
  let timeOffset = 0;
  let idx = 1;
  const blocks: string[] = [];
  for (const scene of ordered) {
    const cap = captions.find((c) => c.scene_id === scene.id);
    const dur = scene.estimated_seconds ?? 0;
    if (cap?.caption_lines?.length) {
      for (const line of cap.caption_lines) {
        const start = formatSRTTime(line.start + timeOffset);
        const end = formatSRTTime(line.end + timeOffset);
        blocks.push(`${idx}\n${start} --> ${end}\n${line.text}\n`);
        idx += 1;
      }
    }
    timeOffset += dur;
  }
  return blocks.join("\n");
}

export function buildPlatformManifestNotes(platforms: ExportPlatform[]): string {
  if (!platforms.length) return "";
  return [
    "PLATFORM TARGETS",
    "Generated by DocForge",
    "",
    ...platforms.map((p) => `- ${PLATFORM_NOTES[p]}`),
  ].join("\n");
}

/* ------------------------------ FOLDER TREE ------------------------------- */

export function buildFolderPreview(
  selections: ExportSelections,
  inputs: ExportInputs,
  platforms: ExportPlatform[],
): string[] {
  const slug = slugify(inputs.project.title);
  const root = `${slug}_docforge_export`;
  const lines: string[] = [`/${root}/`];

  const docs: string[] = [];
  if (selections.manifest_json && inputs.manifest)
    docs.push(`manifest_v${inputs.manifest.version}.json`);
  if (selections.manifest_pdf && inputs.manifest)
    docs.push(`manifest_v${inputs.manifest.version}.pdf`);
  if (selections.manifest_markdown && inputs.manifest)
    docs.push(`manifest_v${inputs.manifest.version}.md`);
  if (selections.editor_brief && inputs.manifest) docs.push("editor_brief.txt");
  if (selections.metadata_json && inputs.videoMetadata) docs.push("metadata.json");
  if (platforms.length) docs.push("platform_targets.txt");
  if (docs.length) {
    lines.push("  /documents/");
    for (const f of docs) lines.push(`    ${f}`);
  }

  if (selections.voiceovers && inputs.voiceovers.length) {
    lines.push("  /audio/voiceovers/");
    lines.push("    voiceover_files.json");
    lines.push("    DOWNLOAD_INSTRUCTIONS.txt");
  }

  const vis: string[] = [];
  if (selections.clip_references) vis.push("clip_references.json");
  if (selections.ai_images) vis.push("ai_images.json");
  if (selections.hera_videos) vis.push("hera_videos.json");
  if (selections.motion_graphic_specs) vis.push("motion_graphic_specs.json");
  if (vis.length) {
    lines.push("  /visuals/");
    for (const f of vis) lines.push(`    ${f}`);
  }

  const prompts: string[] = [];
  if (selections.ai_clip_prompts) prompts.push("ai_clip_prompts.txt");
  if (selections.thumbnail_concepts && inputs.thumbnail) prompts.push("thumbnail_concepts.txt");
  if (prompts.length) {
    lines.push("  /prompts/");
    for (const f of prompts) lines.push(`    ${f}`);
  }

  const meta: string[] = [];
  if (selections.youtube_metadata && inputs.videoMetadata) meta.push("youtube_metadata.txt");
  if (selections.platform_copy && inputs.videoMetadata) meta.push("platform_copy.txt");
  if (meta.length) {
    lines.push("  /metadata/");
    for (const f of meta) lines.push(`    ${f}`);
  }

  const captionsHas = inputs.captions.length > 0;
  if ((selections.full_srt || selections.per_scene_srt) && captionsHas) {
    lines.push("  /captions/");
    if (selections.full_srt) lines.push("    full_video_captions.srt");
    if (selections.per_scene_srt) {
      lines.push("    /per_scene/");
      for (const s of [...inputs.scenes].sort((a, b) => a.scene_index - b.scene_index)) {
        const cap = inputs.captions.find((c) => c.scene_id === s.id);
        if (cap?.srt_content) lines.push(`      scene_${pad2(s.scene_index + 1)}_captions.srt`);
      }
    }
  }

  return lines;
}

export function countSelectedFiles(
  selections: ExportSelections,
  inputs: ExportInputs,
  platforms: ExportPlatform[],
): number {
  return buildFolderPreview(selections, inputs, platforms).filter((l) => !l.trim().endsWith("/"))
    .length;
}

export function estimatedSizeMB(selections: ExportSelections, inputs: ExportInputs): number {
  // Pure compilation — no media is embedded. Estimate JSON/text payload.
  let bytes = 0;
  if (selections.manifest_json && inputs.manifest)
    bytes += JSON.stringify(inputs.manifest.manifest_data ?? {}).length;
  if (selections.manifest_markdown && inputs.manifest) bytes += 8000;
  if (selections.editor_brief) bytes += 2000;
  if (selections.metadata_json && inputs.videoMetadata)
    bytes += JSON.stringify(inputs.videoMetadata).length;
  if (selections.clip_references) bytes += inputs.clips.length * 400;
  if (selections.ai_images) bytes += inputs.clips.length * 300;
  if (selections.hera_videos) bytes += inputs.clips.length * 200;
  if (selections.motion_graphic_specs) bytes += inputs.motionGraphics.length * 500;
  if (selections.ai_clip_prompts) bytes += inputs.scenes.length * 400;
  if (selections.thumbnail_concepts && inputs.thumbnail) bytes += 4000;
  if (selections.youtube_metadata && inputs.videoMetadata) bytes += 2000;
  if (selections.platform_copy && inputs.videoMetadata) bytes += 2000;
  if (selections.full_srt) bytes += inputs.captions.length * 2000;
  if (selections.per_scene_srt) bytes += inputs.captions.length * 2000;
  if (selections.voiceovers) bytes += inputs.voiceovers.length * 300;
  return Math.max(0.01, +(bytes / (1024 * 1024)).toFixed(2));
}

/* --------------------------- ASSET URL EXTRACTION ------------------------- */

export function collectAssetUrls(inputs: ExportInputs): string[] {
  const urls = new Set<string>();
  for (const v of inputs.voiceovers) if (v.audio_url) urls.add(v.audio_url);
  for (const c of inputs.clips) {
    if (c.source_url) urls.add(c.source_url);
    if (c.image_url) urls.add(c.image_url);
    if (c.animation_url) urls.add(c.animation_url);
    if (c.thumbnail_url) urls.add(c.thumbnail_url);
  }
  for (const mg of inputs.motionGraphics) if (mg.hera_output_url) urls.add(mg.hera_output_url);
  if (inputs.thumbnail) {
    for (const c of (inputs.thumbnail.concepts ?? []) as Record<string, unknown>[]) {
      if (typeof c.image_url === "string") urls.add(c.image_url);
    }
  }
  return Array.from(urls);
}

