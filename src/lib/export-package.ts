export function buildYouTubeMetadataTxt(meta: VideoMetadataRecord): string {
  const titles = meta.titles as { text?: string }[];
  const firstTitle =
    typeof titles?.[0] === "string" ? (titles[0] as unknown as string) : titles?.[0]?.text;
  return `YOUTUBE METADATA
Generated by DocForge

TITLE
${meta.selected_title ?? firstTitle ?? ""}

DESCRIPTION
${meta.description ?? ""}

${(meta.hashtags ?? []).join(" ")}

TAGS
${(meta.tags ?? []).join(", ")}

CHAPTERS
${(meta.chapters ?? []).map((c) => `${c.time} ${c.title}`).join("\n")}
`;
}

