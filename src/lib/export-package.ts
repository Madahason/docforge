export type ProgressFn = (msg: string) => void;

export async function buildExportZip(
  inputs: ExportInputs,
  selections: ExportSelections,
  platforms: ExportPlatform[],
  onProgress: ProgressFn,
): Promise<Blob> {
  const zip = new JSZip();
  const slug = slugify(inputs.project.title);
  const root = zip.folder(`${slug}_docforge_export`);
  if (!root) throw new Error("Failed to create zip root");

  // DOCUMENTS
  onProgress("Adding manifest…");
  const docs = root.folder("documents");
  if (docs && inputs.manifest) {
    const data = inputs.manifest.manifest_data as ManifestData;
    if (selections.manifest_json)
      docs.file(`manifest_v${inputs.manifest.version}.json`, JSON.stringify(data, null, 2));
    if (selections.manifest_markdown)
      docs.file(`manifest_v${inputs.manifest.version}.md`, manifestToMarkdown(data));
    if (selections.manifest_pdf) {
      // PDF generation requires a renderer; ship a print-ready HTML alongside the markdown.
      docs.file(
        `manifest_v${inputs.manifest.version}.pdf.html`,
        `<!doctype html><meta charset="utf-8"><title>Manifest v${inputs.manifest.version}</title><pre style="font-family:ui-monospace,Menlo,monospace;white-space:pre-wrap;padding:24px;">${escapeHtml(
          manifestToMarkdown(data),
        )}</pre><script>window.onload=()=>window.print();</script>`,
      );
    }
    if (selections.editor_brief)
      docs.file("editor_brief.txt", buildEditorBriefTxt(data, inputs.project));
  }
  if (selections.metadata_json && inputs.videoMetadata && docs) {
    docs.file("metadata.json", JSON.stringify(inputs.videoMetadata, null, 2));
  }
  if (platforms.length && docs) {
    docs.file("platform_targets.txt", buildPlatformManifestNotes(platforms));
  }

  // AUDIO
  if (selections.voiceovers && inputs.voiceovers.length) {
    onProgress("Adding voiceovers…");
    const audio = root.folder("audio")?.folder("voiceovers");
    if (audio) {
      const refs = inputs.voiceovers
        .filter((v) => v.audio_url)
        .map((v) => {
          const n = sceneNumberOf(inputs.scenes, v.scene_id);
          return {
            scene: n,
            filename: `scene_${pad2(n)}_voiceover.mp3`,
            url: v.audio_url,
            duration_seconds: v.duration_seconds,
            voice_name: v.voice_name,
            words_per_minute: v.words_per_minute,
          };
        })
        .sort((a, b) => a.scene - b.scene);
      audio.file("voiceover_files.json", JSON.stringify(refs, null, 2));
      audio.file(
        "DOWNLOAD_INSTRUCTIONS.txt",
        "Each voiceover is hosted as an MP3.\n" +
          "Download from the `url` field in voiceover_files.json,\n" +
          "and rename to the matching `filename`.\n",
      );
    }
  }

  // VISUALS
  onProgress("Adding visual references…");
  const visuals = root.folder("visuals");
  if (visuals) {
    if (selections.clip_references) {
      const refs = inputs.clips
        .filter((c) => c.asset_type === "youtube" || c.asset_type === "stock_footage")
        .map((c) => ({
          scene: sceneNumberOf(inputs.scenes, c.scene_id),
          type: c.asset_type,
          source: c.source_channel,
          title: c.source_title,
          url: c.source_url,
          timestamp_start: c.timestamp_start,
          timestamp_end: c.timestamp_end,
          duration_seconds: c.duration_seconds,
        }))
        .sort((a, b) => a.scene - b.scene);
      visuals.file("clip_references.json", JSON.stringify(refs, null, 2));
    }
    if (selections.ai_images) {
      const refs = inputs.clips
        .filter((c) => c.asset_type === "static_image" || c.image_url)
        .map((c) => ({
          scene: sceneNumberOf(inputs.scenes, c.scene_id),
          image_url: c.image_url,
          source: c.source_channel,
          ken_burns: c.ken_burns_config,
        }))
        .sort((a, b) => a.scene - b.scene);
      visuals.file("ai_images.json", JSON.stringify(refs, null, 2));
    }
    if (selections.hera_videos) {
      const refs = inputs.motionGraphics
        .filter((mg) => mg.hera_output_url)
        .map((mg) => ({
          scene: sceneNumberOf(inputs.scenes, mg.scene_id),
          graphic_type: mg.graphic_type,
          output_url: mg.hera_output_url,
          render_method: mg.render_method,
        }))
        .sort((a, b) => a.scene - b.scene);
      visuals.file("hera_videos.json", JSON.stringify(refs, null, 2));
    }
    if (selections.motion_graphic_specs) {
      const specs = inputs.motionGraphics.map((mg) => ({
        scene: sceneNumberOf(inputs.scenes, mg.scene_id),
        graphic_type: mg.graphic_type,
        graphic_data: mg.graphic_data,
        render_method: mg.render_method,
        remotion_component: mg.graphic_type
          .split("_")
          .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : ""))
          .join(""),
      }));
      visuals.file("motion_graphic_specs.json", JSON.stringify(specs, null, 2));
    }
  }

  // PROMPTS
  const prompts = root.folder("prompts");
  if (prompts) {
    if (selections.ai_clip_prompts) {
      prompts.file("ai_clip_prompts.txt", buildAiClipPromptsTxt(inputs.scenes, inputs.clips));
    }
    if (selections.thumbnail_concepts && inputs.thumbnail) {
      prompts.file("thumbnail_concepts.txt", buildThumbnailConceptsTxt(inputs.thumbnail));
    }
  }

  // METADATA
  if (inputs.videoMetadata) {
    const meta = root.folder("metadata");
    if (meta) {
      if (selections.youtube_metadata)
        meta.file("youtube_metadata.txt", buildYouTubeMetadataTxt(inputs.videoMetadata));
      if (selections.platform_copy)
        meta.file("platform_copy.txt", buildPlatformCopyTxt(inputs.videoMetadata));
    }
  }

  // CAPTIONS
  onProgress("Adding captions…");
  if (selections.full_srt && inputs.captions.length) {
    const captionsFolder = root.folder("captions");
    captionsFolder?.file(
      "full_video_captions.srt",
      buildFullVideoSrt(inputs.scenes, inputs.captions),
    );
  }
  if (selections.per_scene_srt && inputs.captions.length) {
    const perScene = root.folder("captions")?.folder("per_scene");
    if (perScene) {
      for (const s of [...inputs.scenes].sort((a, b) => a.scene_index - b.scene_index)) {
        const cap = inputs.captions.find((c) => c.scene_id === s.id);
        if (cap?.srt_content) {
          perScene.file(`scene_${pad2(s.scene_index + 1)}_captions.srt`, cap.srt_content);
        }
      }
    }
  }

  // README
  root.file(
    "README.txt",
    `DocForge Export Package
Project: ${inputs.project.title}
Duration: ${
      inputs.manifest
        ? formatTimecode(
            (inputs.manifest.manifest_data as ManifestData)?.project?.total_duration_seconds ?? 0,
          )
        : "—"
    }
Manifest version: ${inputs.manifest?.version ?? "—"}
Platforms: ${platforms.map((p) => PLATFORM_LABELS[p]).join(", ") || "—"}

All large media assets are referenced by URL.
See documents/, visuals/, audio/, captions/ for the full package.
`,
  );

  onProgress("Compressing…");
  const blob = await zip.generateAsync({
    type: "blob",
    compression: "DEFLATE",
    compressionOptions: { level: 6 },
  });
  return blob;
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export function triggerDownload(blob: Blob, filename: string): string {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  // Return URL so caller can revoke later or use for "download again"
  return url;
}
