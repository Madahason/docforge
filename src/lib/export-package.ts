export type ExportPlatform = "youtube" | "youtube_shorts" | "linkedin" | "twitter";

export const PLATFORM_LABELS: Record<ExportPlatform, string> = {
  youtube: "YouTube (16:9)",
  youtube_shorts: "YouTube Shorts (9:16)",
  linkedin: "LinkedIn (16:9)",
  twitter: "Twitter (16:9 compressed)",
};

export const PLATFORM_NOTES: Record<ExportPlatform, string> = {
  youtube: "YouTube (16:9): Standard 1920x1080 export. 30fps, H.264, AAC 320kbps audio.",
  youtube_shorts:
    "YouTube Shorts (9:16): Identify strongest 60-second moment. Reformat to 9:16 vertical. Add captions (required for Shorts). Recommend the highest-tension scene.",
  linkedin:
    "LinkedIn (16:9): Trim to under 10 minutes. Add captions (autoplay muted). First 3 seconds must work without sound.",
  twitter:
    "Twitter / X (16:9 compressed): Trim to under 2 minutes 20 seconds. Compress for web. Captions required.",
};

export type ExportInputs = {
  project: ProjectRecord;
  scenes: Scene[];
  voiceovers: Voiceover[];
  clips: Clip[];
  motionGraphics: MotionGraphicRecord[];
  captions: CaptionRecord[];
  manifest: ManifestSummary | null;
  thumbnail: ThumbnailRecord | null;
  videoMetadata: VideoMetadataRecord | null;
};

export function slugify(s: string): string {
  return (s || "project")
    .replace(/[^a-z0-9]+/gi, "_")
    .toLowerCase()
    .replace(/^_|_$/g, "");
}

function sceneNumberOf(scenes: Scene[], scene_id: string): number {
  const s = scenes.find((x) => x.id === scene_id);
  return s ? s.scene_index + 1 : 0;
}

function pad2(n: number) {
  return String(n).padStart(2, "0");
}

